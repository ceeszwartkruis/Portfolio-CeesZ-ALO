function renderParagraphs(elementId, paragraphs) {
  const element = document.getElementById(elementId);
  element.innerHTML = paragraphs.map(paragraph => `<p>${paragraph}</p>`).join("");
}

function renderCards(elementId, cards) {
  const element = document.getElementById(elementId);
  element.innerHTML = cards.map(card => `
    <article class="card">
      <span class="tag">${card.tag}</span>
      <h3>${card.title}</h3>
      <p>${card.text}</p>
    </article>
  `).join("");
}

function renderTimeline(elementId, items) {
  const element = document.getElementById(elementId);
  element.innerHTML = items.map(item => `
    <article class="timeline-item">
      <span>${item.period}</span>
      <h3>${item.title}</h3>
      <p>${item.text}</p>
    </article>
  `).join("");
}

